"""Generate parse_nl's raw vocabulary resource and compile-time metadata."""

from __future__ import annotations

import argparse
import ast
import binascii
import re
import sys
import tempfile
from pathlib import Path


EXPECTED_BLOB_COUNT = 26
DEFINITION_RE = re.compile(
    r'^NL_BLOB\(([A-Z][A-Z0-9_]*_BLOB),\s*("(?:\\.|[^"\\])*")\)$'
)


def read_definitions(path: Path) -> list[tuple[str, bytes]]:
    definitions: list[tuple[str, bytes]] = []
    seen: set[str] = set()
    for line_number, raw_line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw_line.strip()
        if not line or line.startswith("//"):
            continue
        match = DEFINITION_RE.fullmatch(line)
        if match is None:
            raise ValueError(f"{path}:{line_number}: malformed NL_BLOB definition")
        name, literal = match.groups()
        if name in seen:
            raise ValueError(f"{path}:{line_number}: duplicate blob {name}")
        value = ast.literal_eval(literal)
        if not isinstance(value, str) or not value.endswith("\0"):
            raise ValueError(f"{path}:{line_number}: {name} must end with an explicit NUL")
        try:
            encoded = value.encode("ascii") + b"\0"
        except UnicodeEncodeError as error:
            raise ValueError(f"{path}:{line_number}: {name} must contain ASCII bytes only") from error
        if b"\0\0" in encoded[:-2]:
            raise ValueError(f"{path}:{line_number}: {name} contains an empty interior entry")
        definitions.append((name, encoded))
        seen.add(name)

    if len(definitions) != EXPECTED_BLOB_COUNT:
        raise ValueError(
            f"{path}: expected {EXPECTED_BLOB_COUNT} blobs, found {len(definitions)}"
        )
    return definitions


def render_header(definitions: list[tuple[str, bytes]], payload: bytes) -> bytes:
    lines = [
        "// Generated by scripts/generate_nl_tables.py. DO NOT EDIT.",
        "#pragma once",
        "",
        f"#define NL_TABLES_TOTAL {len(payload)}u",
        f"#define NL_TABLES_CRC32 0x{binascii.crc32(payload) & 0xFFFFFFFF:08x}u",
        f"#define NL_TABLES_BLOB_COUNT {len(definitions)}u",
        "",
    ]
    offset = 0
    for name, value in definitions:
        word_count = len([entry for entry in value.split(b"\0") if entry != b""])
        lines.append(f"#define NL_OFFSET_{name} {offset}u")
        lines.append(f"#define NL_SIZE_{name} {len(value)}u")
        lines.append(f"#define NL_WORD_COUNT_{name} {word_count}u")
        offset += len(value)

    lines.extend(["", "#ifdef NL_TABLES_BASE"])
    offset = 0
    for name, value in definitions:
        lines.append(
            f"#define {name} "
            f"(*(const char (*)[{len(value)}u])((NL_TABLES_BASE) + {offset}u))"
        )
        offset += len(value)
    lines.extend(["#endif", ""])
    return "\n".join(lines).encode("ascii")


def render_host_include(payload: bytes) -> bytes:
    lines = [
        "// Generated by scripts/generate_nl_tables.py. DO NOT EDIT.",
        f"static const uint8_t NL_TABLES_HOST_DATA[{len(payload)}] = {{",
    ]
    for start in range(0, len(payload), 16):
        chunk = payload[start : start + 16]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.extend(["};", ""])
    return "\n".join(lines).encode("ascii")


def write_atomic_if_changed(path: Path, content: bytes) -> None:
    if path.exists() and path.read_bytes() == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as handle:
        handle.write(content)
        temporary = Path(handle.name)
    temporary.replace(path)


def verify_outputs(
    binary_path: Path,
    header_path: Path,
    host_include_path: Path,
    payload: bytes,
    header: bytes,
    host_include: bytes,
) -> None:
    outputs = (
        (binary_path, payload),
        (header_path, header),
        (host_include_path, host_include),
    )
    for path, expected in outputs:
        actual = path.read_bytes()
        if actual != expected:
            raise ValueError(f"generated output verification failed: {path}")

    crc = binascii.crc32(binary_path.read_bytes()) & 0xFFFFFFFF
    checksum_line = f"#define NL_TABLES_CRC32 0x{crc:08x}u".encode("ascii")
    if checksum_line not in header_path.read_bytes():
        raise ValueError("generated binary/header checksum drift")


def main() -> int:
    parser = argparse.ArgumentParser()
    app_dir = Path(__file__).resolve().parent.parent
    parser.add_argument(
        "--source",
        type=Path,
        default=app_dir / "src/c/lib/parse_nl_vocab.def",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=app_dir / "resources/generated",
    )
    args = parser.parse_args()

    try:
        definitions = read_definitions(args.source)
        payload = b"".join(value for _, value in definitions)
        header = render_header(definitions, payload)
        host_include = render_host_include(payload)

        binary_path = args.out_dir / "nl_tables.bin"
        header_path = args.out_dir / "nl_tables.h"
        host_include_path = args.out_dir / "nl_tables_host.inc"
        write_atomic_if_changed(binary_path, payload)
        write_atomic_if_changed(header_path, header)
        write_atomic_if_changed(host_include_path, host_include)
        verify_outputs(
            binary_path,
            header_path,
            host_include_path,
            payload,
            header,
            host_include,
        )
    except (OSError, SyntaxError, ValueError) as error:
        print(f"generate_nl_tables: error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
